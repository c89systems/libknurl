local knurl=require('knurl')
local input=knurl.input
local function invalid(fn,...)
  local value,err=fn(...)
  assert(value==nil and err.status==knurl.status.INVALID)
end
assert(input.parse_long('-42',-42,42)==-42)
invalid(input.parse_long,'+42');invalid(input.parse_long,' 1')
invalid(input.parse_long,'1\0junk');invalid(input.parse_long,'3',0,2)
assert(tostring(input.parse_u64('18446744073709551615'))=='18446744073709551615')
local value,err=input.parse_u64('18446744073709551616')
assert(value==nil and err.status==knurl.status.OVERFLOW)
assert(input.boolean('true')==true and input.boolean('false')==false)
invalid(input.boolean,'True');invalid(input.boolean,1)
assert(input.text('hello €',0,9,true));invalid(input.text,'\192\128')
invalid(input.text,'a\0b');invalid(input.text,'a\nb',0,100,true)
assert(input.allowlist('ab','abc',0,2));invalid(input.allowlist,'ab!','abc')
assert(input.choice('red',{'red','blue'}));invalid(input.choice,'RED',{'red'})
assert(input.email('user+tag@example.org'));invalid(input.email,'a..b@host')
assert(input.http_url('HTTPS://example.org:443/'));invalid(input.http_url,'example.org')
invalid(input.http_url,'https://user@host');invalid(input.http_url,'https://host:99999')
assert(input.filename('a_b.txt'));invalid(input.filename,'../a')
assert(input.html_escape([[<&"'>]])=='&lt;&amp;&quot;&#39;&gt;')
value,err=input.html_escape('<',3)
assert(value==nil and err.status==knurl.status.LIMIT)
for n=0,30 do
  fixture.fail_call(n,function() input.html_escape(string.rep('<',100)) end)
  fixture.fail_call(n,function() input.choice('a',{'a','b'}) end)
end
collectgarbage('collect')
